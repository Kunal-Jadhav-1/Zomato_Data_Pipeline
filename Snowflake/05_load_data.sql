USE ROLE ACCOUNTADMIN;
USE DATABASE ZOMATO;
USE SCHEMA RAW;
USE WAREHOUSE ZOMATO_WH;

COPY INTO RAW.RESTAURANT FROM @ZOMATO_RAW_STAGE/restaurant ON_ERROR='CONTINUE'; -- RAW.RESTAURANT
COPY INTO RAW.REVIEWS FROM @ZOMATO_RAW_STAGE/reviews ON_ERROR='CONTINUE'; --- RAW.REVIEWS
COPY INTO RAW.USERS FROM @ZOMATO_RAW_STAGE/users ON_ERROR='CONTINUE'; -- RAW.USERS
COPY INTO RAW.ORDER_ITEMS FROM @ZOMATO_RAW_STAGE/order_items ON_ERROR='CONTINUE'; -- RAW.ORDER_ITEMS
COPY INTO RAW.ORDERS FROM @ZOMATO_RAW_STAGE/orders ON_ERROR='CONTINUE'; -- RAW.ORDERS
COPY INTO RAW.FOOD FROM @ZOMATO_RAW_STAGE/food ON_ERROR='CONTINUE'; -- RAW.FOOD
COPY INTO RAW.MENU FROM @ZOMATO_RAW_STAGE/menu ON_ERROR='CONTINUE'; -- RAW.MENU

SELECT 'FOOD' as tables_,COUNT(*) as rows_ FROM RAW.FOOD UNION ALL
SELECT 'ORDERS',COUNT(*) FROM RAW.ORDERS UNION ALL
SELECT 'MENU',COUNT(*) FROM RAW.MENU UNION ALL
SELECT 'ORDER_ITEMS',COUNT(*) FROM RAW.ORDER_ITEMS UNION ALL
SELECT 'USERS',COUNT(*) FROM RAW.USERS UNION ALL
SELECT 'REVIEWS',COUNT(*) FROM RAW.REVIEWS UNION ALL
SELECT 'RESTAURANT',COUNT(*) FROM RAW.RESTAURANT;
